
using System;
using System.Linq;
using System.Reflection;
using System.Threading;
using RimWorld;
using RimWorld.Planet;
using UnityEngine;
using Verse;

/// <summary>
/// Runs inside the game process: waits for boot completion, then executes the scenario.
/// BootCompleted is raised from Bootstrap.RaiseBootCompleteOnce on the main thread, i.e. after
/// PlayDataLoader.Loaded is true and the def database is final.
/// </summary>
internal static class StartupHook
{
    private static int _ran;

    public static void Initialize()
    {
        var thread = new Thread(WaitForBoot) { IsBackground = true, Name = "scenario-waiter" };
        thread.Start();
    }

    private static void WaitForBoot()
    {
        while (Waylith.Runtime.WaylithRuntime.Current == null) Thread.Sleep(20);
        Waylith.Runtime.WaylithRuntime.Current.App.BootCompleted += Run;
        Console.Error.WriteLine("[scenario] boot hook armed");
    }

    private static void Run()
    {
        if (Interlocked.Exchange(ref _ran, 1) != 0) return;
        try
        {
            Body();
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine("[SCENARIO] EXCEPTION " + ex);
            Console.Error.WriteLine("[SCENARIO] RESULT=FAIL");
        }
    }

    private static void Body()
    {
        Console.Error.WriteLine($"[SCENARIO] boot=completo programState={Current.ProgramState}");

        // ---- 1. the real def database, as loaded from Data/*/Defs -------------------------
        var thingDefs = DefDatabase<ThingDef>.AllDefsListForReading;
        Console.Error.WriteLine($"[SCENARIO] defs.thingDefs={thingDefs.Count}");
        Console.Error.WriteLine($"[SCENARIO] defs.all={DefDatabase<Def>.AllDefsListForReading.Count}");

        var uniques = thingDefs.Where(d => d.comps != null &&
                                           d.comps.Any(c => c != null && c.GetType().Name.Contains("UniqueWeapon")))
                               .ToList();
        Console.Error.WriteLine($"[SCENARIO] uniqueWeaponDefs={uniques.Count} " +
                                string.Join(",", uniques.Take(6).Select(d => d.defName)));

        ThingDef target = uniques.FirstOrDefault(d => d.defName == "Gun_Revolver_Unique")
                          ?? uniques.FirstOrDefault()
                          ?? DefDatabase<ThingDef>.GetNamedSilentFail("Gun_Revolver");
        if (target == null)
        {
            Console.Error.WriteLine("[SCENARIO] RESULT=FAIL reason=no-weapon-def");
            return;
        }
        Console.Error.WriteLine($"[SCENARIO] target.defName={target.defName} label='{target.label}' " +
                                $"graphic={(target.graphic == null ? "<null>" : target.graphic.GetType().Name)} " +
                                $"texPath={target.graphicData?.texPath}");

        // ---- 2. a real map, generated by the game's own MapGenerator ---------------------
        string mapResult;
        try
        {
            // The world generator asks Find.Scenario for its planet layers, so a scenario has to be
            // in place before GenerateWorld(): this is the same object the "Crashlanded" scenario def
            // gives the new-colony flow.
            Current.Game = new Game();
            ScenarioDef scenDef = DefDatabase<ScenarioDef>.GetNamedSilentFail("Crashlanded")
                                  ?? DefDatabase<ScenarioDef>.AllDefs.FirstOrDefault();
            if (scenDef != null) Current.Game.Scenario = scenDef.scenario;
            Current.Game.InitData = new GameInitData();
            Console.Error.WriteLine($"[SCENARIO] scenario={(scenDef == null ? "<null>" : scenDef.defName)}");
            Current.Game.World = WorldGenerator.GenerateWorld(0.3f, "waylith-headless-ci",
                OverallRainfall.Normal, OverallTemperature.Normal, OverallPopulation.Normal,
                LandmarkDensity.Normal);
            Console.Error.WriteLine($"[SCENARIO] world=OK tiles={Find.WorldGrid.TilesCount}");
            Map map = MapGenerator.GenerateMap(new IntVec3(75, 1, 75), null, MapGeneratorDefOf.Base_Faction);
            Current.Game.CurrentMap = map;
            mapResult = $"OK size={map.Size.x}x{map.Size.z} things={map.listerThings.AllThings.Count} " +
                        $"terrainCells={map.cellIndices.NumGridCells}";
        }
        catch (Exception ex)
        {
            mapResult = $"FAILED {ex.GetType().Name}: {ex.Message}";
            Console.Error.WriteLine("[SCENARIO] map stack:\n" + ex);
        }
        Console.Error.WriteLine($"[SCENARIO] map={mapResult}");

        // ---- 3. the icon of that def, through the same call the UI makes ------------------
        // what the texture layer can actually resolve for this def, before asking for the icon
        try
        {
            string dp = Waylith.Runtime.WaylithRuntime.Current.App.DataPath;
            string res = System.IO.Path.Combine(dp, "Resources");
            Console.Error.WriteLine($"[SCENARIO] dataPath={dp} resourcesDir={Waylith.Utils.ResourceFiles.DirectoryExists(res)} " +
                                    $"resourcesFiles={Waylith.Utils.ResourceFiles.EnumerateFiles(res, true).Count()}");
        }
        catch (Exception ex) { Console.Error.WriteLine("[SCENARIO] resource root probe failed: " + ex.Message); }
        try
        {
            string tp = target.graphicData?.texPath;
            if (!tp.NullOrEmpty())
            {
                var folder = ContentFinder<Texture2D>.GetAllInFolder(tp).ToList();
                Console.Error.WriteLine($"[SCENARIO] folder[{tp}] textures={folder.Count} names=" +
                                        string.Join(",", folder.Take(6).Select(t => t.name)));
            }
        }
        catch (Exception ex) { Console.Error.WriteLine("[SCENARIO] folder probe failed: " + ex.Message); }

        string iconResult;
        bool ok;
        try
        {
            Texture2D tex = Widgets.GetIconFor(target);
            Material mat;
            Widgets.GetIconFor(target, out mat);
            bool bad = tex == null || tex == BaseContent.BadTex;
            iconResult = $"def={target.defName} tex={(tex == null ? "<null>" : tex.name)} " +
                         $"size={(tex == null ? "-" : tex.width + "x" + tex.height)} " +
                         $"badTex={bad} uiIcon={(target.uiIcon == null ? "<null>" : target.uiIcon.name)} " +
                         $"material={(mat == null ? "<null>" : mat.name)}";
            ok = !bad;
        }
        catch (Exception ex)
        {
            iconResult = "FAILED " + ex.GetType().Name + ": " + ex.Message;
            Console.Error.WriteLine("[SCENARIO] icon stack:\n" + ex);
            ok = false;
        }
        Console.Error.WriteLine($"[SCENARIO] icon={iconResult}");
        Console.Error.WriteLine($"[SCENARIO] RESULT={(ok ? "OK" : "FAIL")}");
    }
}
